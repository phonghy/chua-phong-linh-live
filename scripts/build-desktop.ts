// Builds the standalone desktop executable. Run with Bun:
//   bun scripts/build-desktop.ts [--target bun-darwin-arm64] [--outfile release/x] [--skip-web]
import { spawnSync } from "node:child_process";
import {
  mkdirSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { join, relative, resolve, sep } from "node:path";

const root = resolve(import.meta.dirname, "..");
const args = process.argv.slice(2);
const option = (name: string) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const hostTarget = `bun-${process.platform === "win32" ? "windows" : process.platform}-${process.arch}`;
const target = option("--target") ?? hostTarget;
const windows = target.includes("windows");
const outfile = resolve(
  root,
  option("--outfile") ??
    `release/ChuaPhongLinh-${target.replace(/^bun-/, "")}${windows ? ".exe" : ""}`,
);
const generated = join(root, "apps/server/src/embedded-assets.gen.ts");
// Source art kept next to the optimised .webp/.png the game actually loads.
const unused = new Set([
  "/assets/altar.png",
  "/assets/temple-hall.png",
  "/assets/visitors-source.png",
]);

const run = (command: string, commandArgs: string[]) => {
  const result = spawnSync(command, commandArgs, {
    cwd: root,
    stdio: "inherit",
    shell: process.platform === "win32" && command === "npm",
  });
  if (result.status !== 0) {
    console.error(`${command} ${commandArgs.join(" ")} failed`);
    process.exit(result.status ?? 1);
  }
};

// A stale generated module would otherwise be type-checked by the web build.
rmSync(generated, { force: true });
if (!args.includes("--skip-web")) run("npm", ["run", "build"]);

const webDir = join(root, "dist/web");
const files: string[] = [];
const walk = (dir: string) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else files.push(path);
  }
};
walk(webDir);
const entries = files
  .map((path) => ({
    path,
    key: "/" + relative(webDir, path).split(sep).join("/"),
  }))
  .filter((entry) => !unused.has(entry.key))
  .sort((a, b) => a.key.localeCompare(b.key));
if (!entries.some((entry) => entry.key === "/index.html"))
  throw new Error("dist/web/index.html is missing; run npm run build.");

writeFileSync(
  generated,
  [
    "// @ts-nocheck",
    "// Generated by scripts/build-desktop.ts. Do not edit or commit.",
    ...entries.map(
      (entry, i) =>
        `import f${i} from ${JSON.stringify(relative(join(root, "apps/server/src"), entry.path).split(sep).join("/"))} with { type: "file" };`,
    ),
    "export const embedded: Record<string, string> = {",
    ...entries.map((entry, i) => `  ${JSON.stringify(entry.key)}: f${i},`),
    "};",
    "",
  ].join("\n"),
);

mkdirSync(resolve(outfile, ".."), { recursive: true });
run(process.execPath, [
  "build",
  "--compile",
  "--minify",
  "--no-compile-autoload-dotenv",
  "--no-compile-autoload-bunfig",
  `--target=${target}`,
  `--outfile=${outfile}`,
  "apps/server/src/desktop.ts",
]);
const megabytes = (statSync(outfile).size / 1048576).toFixed(1);
console.log(
  `Built ${relative(root, outfile)} (${megabytes} MB, ${entries.length} embedded files)`,
);
